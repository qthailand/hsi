"""Generate ``docs/MODULES.md``: one table row per ``modules/*`` package.

Run ``python tools/module_index.py`` after adding or changing a module. The summary is the
first line of the package docstring, so keep that line meaningful (see
docs/MODULE_CONTRACT.md). ``python tools/module_index.py --check`` exits 1 if the committed
file is out of date (used by tests).
"""
from __future__ import annotations

import ast
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT / "tools"))
import module_audit as audit  # noqa: E402

TARGET = ROOT / "docs" / "MODULES.md"


def render() -> str:
    """Return the Markdown index for the current modules."""
    rows = []
    for name in audit.module_names():
        package = audit.MODULES / name
        tree = ast.parse((package / "__init__.py").read_text(encoding="utf-8"))
        summary = (ast.get_docstring(tree) or "").strip().splitlines()[0] if ast.get_docstring(tree) else ""
        report = audit.audit_module(name)
        requires = ", ".join(f"`{r}`" for r in report.requires) or "-"
        widgets = ", ".join(f"`{w}`" for w in report.widgets) or "-"
        standalone = f"`python -m modules.{name}`" if (package / "__main__.py").exists() else "-"
        rows.append(f"| [`{name}`](../modules/{name}/README.md) | {summary} | {requires} | {widgets} | {standalone} |")
    header = (
        "# Modules\n\n"
        "Generated by `python tools/module_index.py` - do not edit by hand. "
        "The rules every module follows are in [MODULE_CONTRACT.md](MODULE_CONTRACT.md).\n\n"
        "| Module | What it is | Requires | Widgets (embeddable) | Stand-alone |\n"
        "|---|---|---|---|---|\n"
    )
    return header + "\n".join(rows) + "\n"


def main(argv=None) -> int:
    """Write (or with ``--check`` verify) ``docs/MODULES.md``; returns the exit code."""
    text = render()
    if argv and "--check" in argv:
        return 0 if TARGET.exists() and TARGET.read_text(encoding="utf-8") == text else 1
    TARGET.write_text(text, encoding="utf-8")
    print(f"wrote {TARGET.relative_to(ROOT)} ({len(audit.module_names())} modules)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main(sys.argv[1:]))
